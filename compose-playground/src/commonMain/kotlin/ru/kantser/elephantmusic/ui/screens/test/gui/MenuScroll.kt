package ru.kantser.elephantmusic.ui.screens.test.gui

/**
 * Чистая логика прокрутки главного меню (без отрисовки и без Compose-состояния).
 *
 * Окно видимости фиксированного размера [VISIBLE_ROWS]: в него всегда помещаются
 * все обычные пункты меню, кроме служебного («Отладка эмулятора») — тот подключается
 * прокруткой, когда выбран. Выбранный пункт всегда остаётся в окне, а само окно
 * сдвигается инкрементно (по одной строке) при его пересечении границы.
 */
object MenuScroll {
    /** Сколько пунктов меню видно в окне экрана (все, кроме последнего служебного). */
    const val VISIBLE_ROWS = 8

    /**
     * Возвращает смещение окна [scroll] после выбора пункта [selected] при общем числе
     * пунктов [items]. Держит выбранный пункт внутри окна, двигая окно ровно настолько,
     * насколько нужно (по одной строке на каждом пересечении границы).
     */
    fun fitScroll(items: Int, scroll: Int, selected: Int): Int {
        val n = minOf(VISIBLE_ROWS, items)
        if (items <= n) return 0
        var s = scroll
        if (selected < s) s = selected
        else if (selected >= s + n) s = selected - n + 1
        return s
    }
}
